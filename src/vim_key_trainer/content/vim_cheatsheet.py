# Standard library imports
from dataclasses import dataclass


@dataclass(frozen=True)
class CheatEntry:
    keys: str
    description: str


@dataclass(frozen=True)
class CheatSection:
    id: str
    title: str
    subtitle: str
    entries: tuple[CheatEntry, ...]
    vim_only: bool = False


def _entries(*rows: tuple[str, str]) -> tuple[CheatEntry, ...]:
    return tuple(CheatEntry(*row) for row in rows)


